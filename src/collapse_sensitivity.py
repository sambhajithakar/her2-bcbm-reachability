#!/usr/bin/env python3
"""Sensitivity of the tiering and the Pareto front to the target-collapsing
decisions recorded in data/target_map.csv.

Collapsing raises a node's cohort count and can therefore raise its tier, so
every contested collapse is re-run with the collapse undone and the result
compared against the primary map.

Usage: collapse_sensitivity.py CENSUS TARGET_MAP SCORES AGENT_MAP OUT_MD
"""
import sys

import pandas as pd

from two_axis_map import NOT_A_TARGET, build_nodes, pareto

# Each scenario undoes one collapse by sending the named census targets back to
# nodes of their own. "none" undoes every collapse at once.
SCENARIOS = {
    "primary": [],
    "split_PIK3CA": ["PIK3CA"],
    "split_immune": ["PD-L1/PD-1 spatial", "CD8-TRM/TLS"],
    "split_HRR_from_HRD": ["HRR/PARP"],
    "split_mTOR_from_PI3K": ["mTOR"],
    "no_collapsing_at_all": "ALL",
}


def _norm(name):
    return "".join(ch for ch in str(name).lower() if ch.isalnum())


def variant_map(target_map, agent_map, undo):
    """Undo a collapse in BOTH maps.

    Splitting a census target off its merged node without moving that target's
    agents leaves the new node with no agents at all, which silently drops it
    from the scored set. The agent map therefore has to follow, matched on the
    normalised target name.
    """
    tmap, amap = target_map.copy(), agent_map.copy()
    if undo == "ALL":
        split = [t for t in tmap.census_target
                 if tmap.loc[tmap.census_target == t, "canonical_target"].iloc[0]
                 not in NOT_A_TARGET]
    else:
        split = list(undo)

    lookup = {_norm(t): t for t in split}
    mask = tmap.census_target.isin(split)
    tmap.loc[mask, "canonical_target"] = tmap.loc[mask, "census_target"]
    amap["canonical_target"] = [
        lookup.get(_norm(a), c)
        for a, c in zip(amap.agents_target, amap.canonical_target)]
    return tmap, amap


def main():
    census_p, map_p, scores_p, agent_map_p, out_p = sys.argv[1:6]
    census = pd.read_csv(census_p)
    target_map = pd.read_csv(map_p)
    scores = pd.read_csv(scores_p)
    agent_map = pd.read_csv(agent_map_p)

    rows, fronts, fronts_norm = [], {}, {}
    for name, undo in SCENARIOS.items():
        tmap, amap = variant_map(target_map, agent_map, undo)
        nodes = build_nodes(census, tmap, scores, amap)
        points = list(zip(nodes.tier_value, nodes.reach))
        front_idx = set(nodes.index[i] for i in pareto(points))
        front = sorted(nodes.loc[sorted(front_idx), "node"])
        # Node labels differ between scenarios only by the separator
        # (PI3K-MTOR vs PI3K/MTOR), so stability is compared on the
        # normalised name, never on the label.
        fronts_norm[name] = {_norm(n) for n in front}
        fronts[name] = front
        tiers = nodes.tier.value_counts().to_dict()
        rows.append({
            "scenario": name,
            "nodes": len(nodes),
            "tier_A": tiers.get("A", 0),
            "tier_B": tiers.get("B", 0),
            "tier_C": tiers.get("C", 0),
            "scored": int(nodes.reach.notna().sum()),
            "front_size": len(front),
            "front": ", ".join(front),
        })

    table = pd.DataFrame(rows)
    primary = fronts_norm["primary"]

    lines = ["# Sensitivity of the result to target collapsing\n",
             "Generated by `src/collapse_sensitivity.py`. Each scenario undoes one "
             "collapse recorded in `data/target_map.csv` and re-runs tiering, the "
             "two-axis map and the Pareto front.\n",
             "| scenario | nodes | A | B | C | scored | front size | Pareto front |",
             "|---|---|---|---|---|---|---|---|"]
    for row in rows:
        lines.append(
            f"| `{row['scenario']}` | {row['nodes']} | {row['tier_A']} | "
            f"{row['tier_B']} | {row['tier_C']} | {row['scored']} | "
            f"{row['front_size']} | {row['front']} |")

    lines.append("\n## What moves\n")
    for name, front in fronts.items():
        if name == "primary":
            continue
        gained = sorted(n for n in front if _norm(n) not in primary)
        lost = sorted(n for n in fronts["primary"] if _norm(n) not in fronts_norm[name])
        if not gained and not lost:
            lines.append(f"- `{name}`: front unchanged.")
        else:
            parts = []
            if gained:
                parts.append("enters: " + ", ".join(gained))
            if lost:
                parts.append("leaves: " + ", ".join(lost))
            lines.append(f"- `{name}`: " + "; ".join(parts) + ".")

    stable_norm = set.intersection(*fronts_norm.values())
    stable = sorted(n for n in fronts["primary"] if _norm(n) in stable_norm)
    fragile = sorted(n for n in fronts["primary"] if _norm(n) not in stable_norm)
    lines.append(
        f"\n**Stable across every scenario:** "
        f"{', '.join(stable) if stable else 'nothing'}.")
    lines.append(
        f"**Dependent on a collapsing decision:** "
        f"{', '.join(fragile) if fragile else 'nothing'}.\n")
    lines.append(
        "A node that appears on the front only under the primary map is an "
        "artefact of a collapsing decision and must be reported as such, not as "
        "a finding.")

    with open(out_p, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
