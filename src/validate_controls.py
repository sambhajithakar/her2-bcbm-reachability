#!/usr/bin/env python3
"""Pre-registered control test (OSF decisions 15-17, failure criterion 1).

The scheme must place tucatinib, trastuzumab deruxtecan and poziotinib high,
and lapatinib and trastuzumab low. The strict test is lapatinib against
tucatinib and poziotinib: same target family, same modality, opposite required
region. Failure is reported as scheme failure and is NOT corrected by
re-weighting.

Usage: validate_controls.py SCORES_CSV OUT_MD
"""
import sys

import pandas as pd

REQUIRED = {
    "tucatinib": "high",
    "trastuzumab-deruxtecan": "high",
    "poziotinib": "high",
    "lapatinib": "low",
    "trastuzumab": "low",
}
HIGH_FLOOR, LOW_CEIL = 0.60, 0.40
STRICT_PAIRS = [("lapatinib", "tucatinib"), ("lapatinib", "poziotinib")]


def main():
    scores_path, out_path = sys.argv[1:3]
    scores = pd.read_csv(scores_path)
    controls = scores[scores.target == "ERBB2"].set_index("agent")

    lines, failures = [], []
    lines.append("# Pre-registered control test\n")
    lines.append("Generated by `src/validate_controls.py`. Criterion: OSF decisions 15-17.\n")
    lines.append("| agent | modality | required | score | band | provenance | verdict |")
    lines.append("|---|---|---|---|---|---|---|")

    for agent, requirement in REQUIRED.items():
        if agent not in controls.index:
            failures.append(f"{agent}: absent from the scored set")
            lines.append(f"| {agent} | - | {requirement} | - | - | - | **FAIL (absent)** |")
            continue
        row = controls.loc[agent]
        score = row["score"]
        if pd.isna(score):
            ok = False
        elif requirement == "high":
            ok = score >= HIGH_FLOOR
        else:
            ok = score <= LOW_CEIL
        if not ok:
            failures.append(f"{agent}: required {requirement}, scored {score}")
        band = f"[{row['lo']:.2f}, {row['hi']:.2f}]" if not pd.isna(score) else "-"
        lines.append(
            f"| {agent} | {row['modality']} | {requirement} | "
            f"{'-' if pd.isna(score) else f'{score:.2f}'} | {band} | "
            f"{row['provenance']} | {'PASS' if ok else '**FAIL**'} |")

    lines.append("\n## Strict test: band separation\n")
    lines.append("| pair | low agent band | high agent band | separated |")
    lines.append("|---|---|---|---|")
    for low_agent, high_agent in STRICT_PAIRS:
        if low_agent not in controls.index or high_agent not in controls.index:
            failures.append(f"{low_agent} vs {high_agent}: one agent missing")
            continue
        low, high = controls.loc[low_agent], controls.loc[high_agent]
        separated = low["hi"] < high["lo"]
        if not separated:
            failures.append(
                f"{low_agent} vs {high_agent}: uncertainty bands overlap, so the "
                "scheme cannot separate them")
        lines.append(
            f"| {low_agent} vs {high_agent} | [{low['lo']:.2f}, {low['hi']:.2f}] | "
            f"[{high['lo']:.2f}, {high['hi']:.2f}] | "
            f"{'yes' if separated else '**no**'} |")

    verdict = "PASS" if not failures else "FAIL"
    lines.insert(2, f"**Verdict: {verdict}**\n")
    if failures:
        lines.append("\n## Failures\n")
        lines.extend(f"- {f}" for f in failures)

    lines.append("""
## What this test does and does not establish

It establishes that the tiered scheme, applied in the pre-registered order,
places five agents against one target where the external evidence says they
belong, and that the uncertainty bands keep the strict pair apart. The three
positive placements rest on a randomized trial, on reported intracranial
responses, and on in vivo imaging in a patient-derived model; none of those
facts is ours.

It does not establish that the curation was blinded. Tier 1 entries were
curated by hand from named sources before this test was run, so for the four
agents resolved at Tier 1 the test checks propagation and band arithmetic
rather than independent discovery. The one genuinely independent placement is
lapatinib's, which B3DB also classifies barrier-negative at Tier 2 without any
input from us. The protocol's remedy is the blinded two-reviewer extraction
(decision 5) and tier-blind scoring (decision 8), neither of which a
single-operator pilot can satisfy. This is reported, not worked around.
""")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit(0 if not failures else 1)


if __name__ == "__main__":
    main()
